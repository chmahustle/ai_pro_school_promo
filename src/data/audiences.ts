export function getAudience(slug: AudienceSlug | string): Audience | undefined {
  return audiences.find((a) => a.slug === slug);
}

/** ЦА в порядке карточек главной */
export function getAudiencesForCards(): Audience[] {
  return audienceCardOrder
    .map((slug) => audiences.find((a) => a.slug === slug))
    .filter((a): a is Audience => Boolean(a));
}

